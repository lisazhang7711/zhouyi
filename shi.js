/* ---------- 取用 ---------- */
function shiOf(n){ return SHI.filter(function(x){ return x.gua === n; }); }
/* 句級命中：只取經文之史與史書用《易》，十翼所稱是通論，不掛在句子上 */
function shiSent(n, kind, i){
  return SHI.filter(function(x){
    return x.gua === n && x.at && x.at[0] === kind && x.at[1] === i && x.cls !== 'yi';
  });
}
function shiHas(n, kind, i){ return shiSent(n, kind, i).length > 0; }

/* 句內〔史〕框：統一為「時 / 人 / 地 / 事 / 疑 / 讀」六行，材料另成引文塊 */
function shiSub(g, kind, i){
  const list = shiSent(g.n, kind, i);
  if (!list.length) return { rows:[[HM('本句'), HM('本句未見可考史事。')]], src:'' };
  let src = '';
  list.forEach(function(x){
    src += '<div class="shblk"><div class="shqt">' + HJ(x.quote) + '</div>'
         + shiRowsHTML(x) + shiSrcHTML(x) + '</div>';
  });
  return { rows:[[HM('本句所涉'), HM('共') + ' ' + list.length + ' ' + HM('條')]], src:src };
}
function shiRowsHTML(x){
  const c = SHI_CONF[x.conf], e = shiEra(x.era);
  const R = [
    [HM('時'), HM(x.tm)],
    [HM('人'), HM(x.who)],
    [HM('地'), HM(x.loc2)],
    [HM('事'), HM(x.evt)],
    [HM('疑'), '<span class="shcf k-' + x.conf + '" title="' + HM(c.d) + '">' + HM(c.nm) + '</span>'
             + '<span class="shtxt">' + HM(x.confT) + '</span>'],
    [HM('讀'), HM(x.use)]
  ];
  return R.map(function(r){
    return '<div class="xsrow"><b>' + r[0] + '</b><span>' + r[1] + '</span></div>'; }).join('');
}
function shiSrcHTML(x){
  const N = { jing:'經', chuan:'傳', chu:'出土' };
  let s = '<div class="shsrc">';
  x.src.forEach(function(y){
    s += '<div class="shsrc1"><span class="shsrc-b k-' + y.k + '" title="'
      + HM(y.k === 'jing' ? '本經' : (y.k === 'chu' ? '出土材料（器物、卜辭）' : '傳世文獻'))
      + '">' + HJ(N[y.k]) + '</span>'
      + '<div class="shsrc-t"><b>' + HJ(y.s) + '</b>'
      + '<div class="yuan">' + HJ(y.t) + '</div>'
      + '<div class="bai">' + HM(y.m) + '</div></div></div>';
  });
  return s + '</div>';
}

