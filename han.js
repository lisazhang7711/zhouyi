const S2T_MAP = {};
const EX = {};
for (const ch of S2T_EXCLUDE) EX[ch] = 1;
for (const t in T2S_MAP) {
  const s = T2S_MAP[t];
  if (!EX[s] && !(s in S2T_MAP)) S2T_MAP[s] = t;
}

/* 一對多歧義字的處理：本站語料是「經文繁體 + 今譯注釋簡體」混排，
 * 同一個簡體字在兩種成分裡要還原成不同的繁體字：
 *   於/于：經文「雲上于天」的「于」是正字，不能動；今譯「求教于」要還原成「於」
 *   後/后：經文「后以財成」的「后」是君主；今譯「之後」要還原成「後」
 *   徵/征：經文「征凶」的「征」是征伐；今譯「象征」要還原成「象徵」
 * 所以分兩條通道：HJ 走經文，HM 走今譯／注釋／介面。 */
const S2T_M_EXTRA = {'于':'於','后':'後','征':'徵','确':'確','划':'劃','范':'範',
                     '悬':'懸','脚':'腳','准':'準','苏':'甦','舍':'捨'};

const S2T_M_MAP = Object.assign({}, S2T_MAP, S2T_M_EXTRA);

function conv(s, map) {
  let out = '';
  for (const ch of s) out += (map[ch] !== undefined ? map[ch] : ch);
  return out;
}
const t2s  = function (s) { return conv(s, T2S_MAP); };   /* 繁 → 簡 */
const s2t  = function (s) { return conv(s, S2T_MAP); };    /* 簡 → 繁（經文用） */
const s2tm = function (s) { return conv(s, S2T_M_MAP); };  /* 簡 → 繁（今譯／註釋／介面用） */

